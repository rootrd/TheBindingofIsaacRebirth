#!/usr/bin/env python3
"""Generate the stack-cleanup table for MSVCP140/VCRUNTIME140 style imports.

Our host shims replace DLL functions, so they must reproduce the callee's
`ret N` exactly: the guest callers were compiled against the real DLLs and rely
on the callee popping its own stack arguments. Hard-coding N per handler by
hand got several of them wrong, which drifts the guest esp and ends up popping
garbage into esi/edi/ebx (the 0xFFFFFFF8 crash). The DLL is authoritative here
-- the mangled name is not, because MSVC lets a caller reserve argument space
the callee then pops.

Reads the import list from the generated guest_imports.c and the exports from
the 32-bit system DLLs, then writes msvcp_ret_table.h.
"""
import struct, sys, os
from capstone import Cs, CS_ARCH_X86, CS_MODE_32

GEN = "/mnt/f/TheBindingofIsaacRebirth/isaac-ohos/entry/src/main/cpp/isaac/generated/guest_imports.c"
OUT = "/mnt/f/TheBindingofIsaacRebirth/isaac-ohos/entry/src/main/cpp/isaac/msvcp_ret_table.h"
DLLS = {
    "MSVCP140.dll":   "/mnt/c/Windows/SysWOW64/MSVCP140.dll",
    "MSVCP140_1.dll": "/mnt/c/Windows/SysWOW64/MSVCP140_1.dll",
    "MSVCP140_2.dll": "/mnt/c/Windows/SysWOW64/MSVCP140_2.dll",
    "VCRUNTIME140.dll":   "/mnt/c/Windows/SysWOW64/VCRUNTIME140.dll",
    "VCRUNTIME140_1.dll": "/mnt/c/Windows/SysWOW64/VCRUNTIME140_1.dll",
}
md = Cs(CS_ARCH_X86, CS_MODE_32)

class PE:
    def __init__(self, path):
        self.data = open(path, "rb").read()
        d = self.data
        e = struct.unpack_from("<I", d, 0x3C)[0]
        coff = e + 4
        nsec, = struct.unpack_from("<H", d, coff + 2)
        optsz, = struct.unpack_from("<H", d, coff + 16)
        opt = coff + 20
        magic, = struct.unpack_from("<H", d, opt)
        assert magic == 0x10B, f"{path}: not PE32"
        self.base, = struct.unpack_from("<I", d, opt + 28)
        dd = opt + 96
        self.exp_rva, _ = struct.unpack_from("<II", d, dd)
        self.secs = []
        so = opt + optsz
        for i in range(nsec):
            b = so + i * 40
            vsize, va, rsize, raw = struct.unpack_from("<IIII", d, b + 8)
            self.secs.append((va, max(vsize, rsize), raw))
        self.exports = self._exports()

    def off(self, rva):
        for va, size, raw in self.secs:
            if va <= rva < va + size:
                return raw + (rva - va)
        return None

    def cstr(self, rva):
        o = self.off(rva)
        return self.data[o:self.data.index(b"\0", o)].decode("latin1")

    def _exports(self):
        if not self.exp_rva:
            return {}
        eo = self.off(self.exp_rva)
        nname = struct.unpack_from("<I", self.data, eo + 24)[0]
        addr_rva = struct.unpack_from("<I", self.data, eo + 28)[0]
        name_rva = struct.unpack_from("<I", self.data, eo + 32)[0]
        ord_rva = struct.unpack_from("<I", self.data, eo + 36)[0]
        out = {}
        for i in range(nname):
            nr, = struct.unpack_from("<I", self.data, self.off(name_rva) + i * 4)
            idx, = struct.unpack_from("<H", self.data, self.off(ord_rva) + i * 2)
            fr, = struct.unpack_from("<I", self.data, self.off(addr_rva) + idx * 4)
            if fr:
                out[self.cstr(nr)] = fr
        return out

    def final_ret(self, rva, hops=0):
        """Total bytes the callee pops (ret N + 4 for the return address)."""
        o = self.off(rva)
        if o is None:
            return None
        for ins in md.disasm(self.data[o:o + 8192], self.base + rva):
            if ins.mnemonic == "ret":
                n = ins.op_str.strip()
                return 4 + (int(n, 0) if n else 0)
            if ins.mnemonic in ("jmp", "jmpq") and hops < 3:
                t = ins.op_str.strip()
                if t.startswith("0x"):
                    return self.final_ret(int(t, 16) - self.base, hops + 1)
                return None
            if ins.mnemonic == "int3":
                return None
        return None

# ---- game imports -----------------------------------------------------------
imports = []
for line in open(GEN):
    line = line.strip()
    if not line.startswith("{ 0x"):
        continue
    name = line.split('"')[1]
    imports.append(name)

dllcache = {}
def ret_of(full):
    dll, _, fn = full.partition("!")
    if dll not in DLLS or not os.path.exists(DLLS[dll]):
        return None
    if dll not in dllcache:
        dllcache[dll] = PE(DLLS[dll])
    pe = dllcache[dll]
    rva = pe.exports.get(fn)
    if rva is None:
        return None
    return pe.final_ret(rva)

rows, missing = [], []
for full in imports:
    if full.split("!")[0] not in DLLS:
        continue
    p = ret_of(full)
    if p is None:
        missing.append(full)
    else:
        rows.append((full, p))

rows.sort()
with open(OUT, "w") as f:
    f.write("/* GENERATED by pc-host/scratch/gen_msvcp_abi.py -- do not edit.\n"
            " * Real stack-cleanup byte counts (return address + popped args) for the\n"
            " * C++ runtime imports, read from the 32-bit system DLLs' `ret N`.\n"
            " * The guest callers rely on the callee popping its own arguments, so a\n"
            " * shim that pops a different amount drifts the guest esp.\n"
            " * Only names present in the game's import table are listed. */\n"
            "#ifndef MSVCP_RET_TABLE_H\n#define MSVCP_RET_TABLE_H\n\n"
            "typedef struct { const char *name; unsigned short pop; } msvcp_ret_entry;\n\n"
            "static const msvcp_ret_entry s_msvcp_rets[] = {\n")
    for name, p in rows:
        f.write(f'    {{ "{name}", {p} }},\n')
    f.write("};\n\n#define MSVCP_RET_COUNT "
            f"((unsigned)(sizeof(s_msvcp_rets)/sizeof(s_msvcp_rets[0])))\n\n"
            "#endif\n")

print(f"wrote {OUT}: {len(rows)} entries, {len(missing)} unresolved")
for m in missing[:20]:
    print("  unresolved:", m)
